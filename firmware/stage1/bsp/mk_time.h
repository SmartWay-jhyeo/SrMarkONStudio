/* 넘치지 않는 밀리초 시계.
 *
 * 🔴 `HAL_GetTick()` 은 32비트라 **49.7일에 한 바퀴 돈다.** 이 보드는
 *    Jetson 에 물려 무인으로 도는 수집 장비이고, 한 바퀴 도는 순간
 *    타임스탬프가 과거로 뛴다. 그 데이터는 시각순으로 정렬되지도 않고,
 *    이미 저장된 것과 뒤섞인다.
 *
 *    큐의 MkSample.t_ms 가 int64_t 인 것도 같은 이유다. 32비트를 그대로
 *    담으면 넓은 타입에 넣어 두기만 하고 값은 이미 접혀 있다.
 *
 * 🔴 분해능은 1 ms 다. 그것이 SysTick 의 한계이고, 3단계의 DRDY 타임스탬프
 *    에는 충분하다 — 가장 빠른 DRATE 에서도 정착이 0.21 ms 인데 실제로
 *    쓰는 것은 60 SPS(16.84 ms)다.
 *
 *    하지만 **PPS 는 이것으로 잡으면 안 된다.** 계획서 §7.3 이 타이머
 *    Input Capture + 오버플로 확장 카운터를 요구한다. Q2 가 PPS 를
 *    HAL_GetTick 으로 잡아 분해능이 1 ms 에 묶인 것이 그대로 옮기면
 *    안 되는 지점이다(CLAUDE.md §1.2).
 */
#ifndef MK_TIME_H
#define MK_TIME_H

#include <stdint.h>

/* 부팅 후 경과 밀리초. 넘치지 않는다.
 *
 * 인터럽트 안에서 불러도 된다 — 내부 갱신을 짧은 임계구역으로 감싼다. */
int64_t mk_time_ms(void);

#endif /* MK_TIME_H */
