/* USART3 송수신 — HAL 을 쓰는 유일한 층.
 *
 * 🔴 app/ 은 HAL 을 모른다. 이 파일이 경계다. 위쪽(mk_hostlink)은 줄만
 *    주고받고, 아래쪽 하드웨어 사정은 전부 여기서 끝난다.
 *
 * 경로: H723 PB10/PB11 (USART3) → F103(BMP) → USB VCP
 *       데이터시트 §7.5 는 이 경로로 통신할 수 없다고 하지만 **틀렸다.**
 *       실기기에서 COM23 으로 NDJSON 이 그대로 나오는 것을 확인했고,
 *       넷리스트에도 경로가 있다 (CLAUDE.md 참조).
 */
#ifndef MK_UART_H
#define MK_UART_H

#include <stddef.h>
#include <stdint.h>

/* 송신 링은 app/ 의 것이다(HAL 비의존). 여기서는 그것을 DMA 에 물리는
 * 일만 한다 — `$STAT` 이 링 상태를 싣기 위해 형을 알아야 한다. */
#include "mk_txring.h"

/* 받은 바이트를 담아 두는 링. 한 줄이 다 모이면 꺼내 쓴다. */
#define MK_RX_RING_SIZE   512

/* 🔴 이 크기를 넘는 줄은 버린다. 규격 §3.1 의 payload 상한이 192 이므로
 *    넉넉하다. 넘치는 입력을 잘라 담으면 앞부분만으로 명령이 되어 버린다. */
#define MK_RX_LINE_MAX    256

void mk_uart_init(uint32_t baud);

/* 속도만 바꾼다 (규격 §4.2). 수신 링과 그 안에 든 바이트는 그대로 둔다.
 *
 * 🔴 **보내던 바이트를 자르지 않는다.** 재설정 전에 셋을 다 기다린다 —
 *    송신 링이 비고, DMA 가 놀고, TC(전송 완료)가 서야 한다. 규격
 *    §4.2.2 규칙 1 이 요구하는 것이 그것이다. 응답의 앞부분만 옛 속도로
 *    나가면 호스트는 그 줄을 읽지 못하고, 성공했는지조차 모르는 채로
 *    링크가 끊긴다. (송신이 DMA 로 바뀌기 전에는 TC 하나면 충분했다 —
 *    2026-08-20.)
 *
 * 🔴 링을 비우지 않는다. 명령이 줄 단위로 걸쳐 있을 수 있고, 여기서
 *    버리면 아직 응답하지 않은 명령이 조용히 사라진다. 옛 속도로 오던
 *    바이트가 새 속도에서 깨져 보이더라도 그것은 프레이밍 계층이
 *    체크섬으로 걸러 낸다. */
void mk_uart_set_baud(uint32_t baud);

/* 한 줄을 송신 링에 넣는다. **즉시 돌아온다** — DMA 가 링에서 꺼내
 * 보내고, 완료 인터럽트가 다음 조각을 잇는다.
 *
 * 🔴 [2026-08-20] 예전에는 `HAL_UART_Transmit`(블로킹)이었다. 실기기에서
 *    그것이 슈퍼루프 한 바퀴를 32 ms 로 늘려 표본이 큐를 넘쳤다 —
 *    7채널 × 10 ms 로 30초를 돌려 채널마다 3000개가 나와야 할 것이
 *    2123개였고, 일곱 채널 전부 drops 853~860 이었다. 링크는 1.5 Mbps 의
 *    36 % 밖에 안 쓰고 있었다. 자세한 계산은 bsp/mk_uart.c 머리말과
 *    app/mk_txring.h.
 *
 * 🔴 자리가 없으면 **줄 통째로** 버린다(잘라 넣지 않는다). 이쪽은 예약
 *    몫까지 쓰므로, 텔레메트리가 링을 채운 상태에서도 명령 응답은 나간다.
 *    판단 근거는 app/mk_txring.h 의 머리말. */
void mk_uart_write(const char *data, size_t len);

/* 텔레메트리용. `mk_uart_write` 와 같지만 명령 응답 몫을 남기고 넣는다 —
 * 링이 그만큼 차 있으면 이 줄은 버려진다.
 *
 * 🔴 이 구분이 없으면, 링크를 포화시킨 그 설정을 되돌리는 `$SACK` 이
 *    나갈 자리가 없어 사람이 아무것도 못 하는 상태가 된다. */
void mk_uart_write_bulk(const char *data, size_t len);

/* 이어서 낼 수 있는 흐름 한 줄 (카탈로그).
 *
 * 🔴 [신설, 2026-08-20] 자리가 없으면 **버리지 않고 0 을 돌려준다.**
 *    부른 쪽이 다음 바퀴에 같은 줄을 다시 준다 — 유실이 아니라 역압이라
 *    계수기도 안 움직인다.
 *
 *    `$CFG,LIST` 가 이것을 쓴다. 103줄 ≈ 25 KB 를 한 번에 쏟던 것이
 *    링(4,096 B)을 넘겨 43줄만 도착했고, 카탈로그는 한 줄만 잃어도
 *    통째로 못 쓰기 때문에 GUI 가 설정 폼을 아예 못 만들었다
 *    (실기기 2026-08-20).
 *
 * 🔴 텔레메트리와 같은 예약 몫을 남긴다. 카탈로그가 링을 끝까지 채우면
 *    그 몇 초 동안 `$SACK`·`$HB` 가 나갈 자리가 없어진다.
 *
 * 반환: 넣었으면 1, 자리가 없으면 0. */
int mk_uart_write_stream(const char *data, size_t len);

/* 링이 차서 버린 줄 수와 바이트 수 (텔레메트리).
 *
 * 🔴 호스트는 이 수를 직접 못 보지만 **알아챌 수 있다** — 버려진 줄의
 *    `seq` 가 비기 때문이다(규격 §7.1). */
uint32_t mk_uart_tx_drops(void);
uint32_t mk_uart_tx_dropped_bytes(void);

/* 제어 경로에서 버린 줄 수와 바이트 수.
 *
 * 🔴 이쪽은 0 이 아니면 그 자체로 경고다. 명령 응답의 `seq` 는 항상 0
 *    이라(규격 §5.2) 호스트가 유실을 알아챌 방법이 이 수 말고는 없다. */
uint32_t mk_uart_tx_ctl_drops(void);
uint32_t mk_uart_tx_ctl_dropped_bytes(void);

/* 아직 안 나간 바이트 수와, 여태 가장 많이 쌓였던 양.
 *
 * 🔴 `peak` 가 링 크기에 붙어 있으면 버린 줄이 0 이어도 다음 번엔
 *    버린다 — 링 크기가 적절한지 실기기에서 볼 수 있는 유일한 수다. */
size_t   mk_uart_tx_pending(void);
uint16_t mk_uart_tx_peak(void);

/* 송신 링 자체. `$STAT` 의 `tx`(규격 §7.4)를 만드는 데 쓴다 —
 * mk_hostlink 가 읽기만 한다.
 *
 * 🔴 이것이 전선에 없어서 이번 결함을 GDB 로 `p 'mk_uart.c'::s_tx` 를
 *    해서야 찾았다. 밖에서 볼 수 없는 계수기는 없는 것과 같다. */
const MkTxRing *mk_uart_tx_ring(void);

/* 송신 DMA 완료 인터럽트에서 부른다. */
void mk_uart_dma_isr(void);

/* 완성된 줄이 있으면 out 에 담고 길이를 돌려준다. 없으면 0.
 *
 * 줄끝은 `\n` 으로 판정한다. `\r` 은 파서가 떼어낸다(규격 §3.2).
 * 반환 길이에 줄끝은 포함되지 않는다. */
size_t mk_uart_read_line(char *out, size_t cap);

/* 링이 넘쳐 버린 바이트 수. 진단용 — 링을 키워야 하는지 알려 준다. */
uint32_t mk_uart_rx_overruns(void);

/* 인터럽트에서 부른다. */
void mk_uart_isr(void);

#endif /* MK_UART_H */
