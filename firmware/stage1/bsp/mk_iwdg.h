/* 독립 워치독 (IWDG1) — 메인 루프가 멈추면 칩이 스스로 리셋한다.
 *
 * 🔴 있는 이유 (사용자 결정 2026-08-22): 젯슨→NRST 직결이 레벨시프터
 *    때문에 불가로 실증되면서(HANDOFF §7.4), "보드가 멈추면 사람이 SW1 을
 *    누르는 수밖에 없다" 가 됐다. IWDG 는 부품 없이 그 구멍의 대부분을
 *    막는다 — CPU 와 무관한 LSI 클럭으로 도는 카운터라, 무한루프든
 *    HardFault 든 메인 루프가 서면 타임아웃(5초, 사용자 지정)에 리셋된다.
 *
 * 🔴 한 번 켜면 리셋 전까지 끌 수 없다 (RM0468 IWDG 장 — 설계 의도).
 *    리셋 후에는 플래시 저장 설정으로 부팅한다 — $CFG,SAVE 안 한 값은
 *    소실되는데, 그것은 NRST 리셋·전원 재투입과 같은 규칙이다.
 */
#ifndef MK_IWDG_H
#define MK_IWDG_H

/* 워치독을 켠다(타임아웃 5초). 슈퍼루프 직전에 한 번 부른다 —
 * 초기화(클럭·LCD 대기 등)가 예산을 먹지 않도록 늦게 켠다. */
void mk_iwdg_init(void);

/* "살아 있다" 도장. 슈퍼루프가 매 바퀴 부른다. */
void mk_iwdg_kick(void);

#endif
