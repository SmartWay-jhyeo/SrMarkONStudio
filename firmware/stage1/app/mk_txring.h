/* 송신 링버퍼 — 슈퍼루프가 넣고 DMA 가 꺼낸다. HAL 비의존.
 *
 * 🔴 왜 생겼나 (실측 2026-08-20)
 *
 *    7채널 × 10 ms, adc.drate=2000, tx.period_ms=10, 링크 1.5 Mbps, 30초:
 *
 *        J3~J9  고유 2123~2124개씩   (3000 이어야 한다)
 *        간격   중앙 10 ms / 최대 30 ms
 *        큐     일곱 채널 모두 depth 64 peak 64 drops 853~860
 *        총     14,863줄 / 30초 = 초당 495줄   (700 이어야 한다)
 *
 *    495 ÷ 16(MK_TELEM_MAX_LINES) = 초당 31 틱 → **슈퍼루프 한 바퀴가
 *    32 ms**. 획득 간격 최대 30 ms 와 정확히 맞물린다. 그런데 링크는
 *    67 KB/s 로 1.5 Mbps(187 KB/s)의 36 % 밖에 안 썼다 — 막고 있던 것은
 *    링크가 아니라 `bsp/mk_uart.c` 의 `HAL_UART_Transmit`(블로킹)이었다.
 *    16줄 × 135 B 를 1.5 Mbps 로 내보내는 14 ms 동안(921600 이면 23 ms)
 *    슈퍼루프가 통째로 서 있었고, 그동안 인터럽트로 계속 들어오던 표본이
 *    큐를 넘쳤다.
 *
 *    수집은 이미 인터럽트로 떼어냈는데(TIM7·DRDY·SPI4 DMA) 송신만 아직
 *    슈퍼루프를 붙잡고 있었다. 이 모듈이 그 마지막 고리를 끊는다.
 *
 * 🔴 계약 — 넣는 쪽은 **즉시** 돌아온다. 완료를 기다리지 않는다.
 *
 * 🔴 계약 — **줄은 절대 잘리지 않는다.** 들어갈 자리가 없으면 한 바이트도
 *    안 넣고 통째로 거절한다(그리고 센다). 들어가는 만큼만 넣으면 NDJSON
 *    한 줄이 가운데서 끊겨 호스트가 깨진 JSON 을 받는데, 그 오류는 링크
 *    문제로 오인된다 — Q2 에서 8개 가설이 전부 기각된 채 미해결로 남은
 *    그 증상(CLAUDE.md §1.2)과 구별이 안 된다.
 *
 * 🔴 왜 기다리지 않고 버리는가 (사용자 판정 기준 2026-08-20:
 *    "센서 값을 늦게 보내도 돼. 무조건 수집을 정상적으로 타임스탬프
 *     찍어서 가지고 있어야해")
 *
 *    링이 찰 만큼 밀렸다면 만드는 양이 링크 용량을 넘은 것이고, 그때는
 *    어디선가 반드시 잃는다. 두 갈래를 비교하면:
 *
 *      기다린다  슈퍼루프가 선다. 그 사이 인터럽트로 들어온 표본이 **모든
 *                채널**의 큐를 넘친다 — 잃는 양이 정지 시간에 비례해
 *                늘어나고, 덤으로 I2C·LCD·din 디바운스·baud 되돌림 시한이
 *                전부 같이 밀린다. 지금 고치려는 그 결함 그대로다.
 *      버린다    이미 만들어진 줄 **하나**를 잃는다. 손실이 그 한 줄로
 *                끝나고, `seq` 가 비어 호스트가 즉시 알아챈다(규격 §7.1).
 *
 *    잃는 양이 한쪽은 무한정이고 한쪽은 한 줄이다. 그래서 버린다.
 *
 * 🔴 예약 몫(reserve) — 텔레메트리가 링을 다 먹으면 `$SACK`·`$ERR` 이
 *    나갈 자리가 없어지고, 사용자는 링크를 포화시킨 그 설정을 되돌릴
 *    수단을 잃는다. 텔레메트리는 예약 몫을 남기고 넣고, 명령 응답은
 *    예약 몫까지 쓴다. mk_linkbaud 의 자동 되돌림과 같은 정신이다 —
 *    사람이 아무것도 못 하는 상태를 만들지 않는다.
 *
 * 🔴 동시성 — 생산자 하나(슈퍼루프), 소비자 하나(DMA 완료 인터럽트)의
 *    SPSC 다. 생산자는 `head` 만, 소비자는 `tail` 만 쓴다. 그래서 잠금이
 *    필요 없다 — 상대의 색인을 **읽기만** 하고, 그 값은 항상 한 방향으로만
 *    움직이므로 낡은 값을 읽어도 보수적인 답(여유를 적게, 보낼 것을 적게)이
 *    된다. mk_queue 가 `count` 하나를 양쪽이 고쳐 임계구역이 필요했던 것과
 *    대비된다(app/mk_queue.h 의 [I3] 주석).
 *
 *    🔴 그래서 `head`·`tail` 은 **둘 다 volatile 이어야 한다.** 최적화기가
 *       루프 안에서 상대의 색인을 레지스터에 담아 두면 인터럽트가 바꾼
 *       값을 영영 못 본다 — 링이 영원히 꽉 찬 것처럼 보이거나(송신 정지)
 *       영원히 빈 것처럼 보인다.
 */
#ifndef MK_TXRING_H
#define MK_TXRING_H

#include <stddef.h>
#include <stdint.h>

typedef struct {
    uint8_t          *buf;
    uint16_t          cap;           /* buf 의 바이트 수 */
    volatile uint16_t head;          /* 다음에 쓸 자리 — 생산자만 쓴다 */
    volatile uint16_t tail;          /* 다음에 보낼 자리 — 소비자만 쓴다 */
    uint32_t          drops;         /* 자리가 없어 통째로 버린 줄 수 */
    uint32_t          dropped_bytes; /* 그 줄들의 바이트 합 */
} MkTxRing;

/* 저장소를 붙인다. 🔴 `buf` 는 **DMA 가 닿는 메모리**여야 한다 —
 * bsp 에서는 MK_DMA_BUF(bsp/mk_dma_mem.h). DTCM 에 두면 전송이 조용히
 * 안 된다. */
void mk_txring_init(MkTxRing *r, uint8_t *buf, uint16_t cap);

/* 지금 들어 있는 바이트 수 / 더 넣을 수 있는 바이트 수.
 *
 * 🔴 쓸 수 있는 칸은 `cap - 1` 이다. `head == tail` 을 '빔' 으로 쓰기로
 *    했으므로 한 칸은 빈 상태와 꽉 찬 상태를 가르는 데 쓴다 — 그 한 칸이
 *    없으면 잠금 없이 두 상태를 구별할 수 없다. */
size_t mk_txring_used(const MkTxRing *r);
size_t mk_txring_free(const MkTxRing *r);

/* 줄을 통째로 넣는다. `reserve` 는 이 호출이 남겨 두어야 할 여유
 * (명령 응답 몫)다 — 텔레메트리는 양수를, 명령 응답은 0 을 준다.
 *
 * 들어갔으면 1, 자리가 없어 통째로 거절했으면 0. **부분 성공은 없다.**
 * 거절은 `drops` 에 센다. 다만 `data == NULL` 이나 `len == 0` 은 유실이
 * 아니므로 세지 않는다. */
int mk_txring_push(MkTxRing *r, const void *data, size_t len, size_t reserve);

/* 다음에 보낼 **연속된** 조각을 가리킨다. 반환은 그 길이(0 이면 빔).
 * 링이 감기는 자리에서 끊어 준다 — DMA 는 연속 메모리만 옮긴다.
 * `out` 이 NULL 이면 길이만 알려 준다. */
size_t mk_txring_chunk(const MkTxRing *r, const uint8_t **out);

/* 보낸 만큼 비운다. 들어 있는 것보다 많이 부르면 0 에서 멈춘다 —
 * 🔴 여기서 tail 이 head 를 넘어가면 used 가 65000 대로 튀어 링이 통째로
 *    망가진다. 링버퍼가 죽는 가장 흔한 방식이라 방어를 둔다. */
void mk_txring_consume(MkTxRing *r, size_t n);

/* 진단 — 링이 차서 버린 줄 수와 바이트 수. `$STAT` 이 싣는다. */
uint32_t mk_txring_drops(const MkTxRing *r);
uint32_t mk_txring_dropped_bytes(const MkTxRing *r);

#endif /* MK_TXRING_H */
