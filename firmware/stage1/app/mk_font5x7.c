static const uint8_t *ascii_glyph(const MkFont *f, uint32_t cp)
{
    (void)f;
    /* 🔴 범위 밖은 NULL 이다. '?' 같은 대체 글자를 몰래 돌려주지 않는다 —
     *    그러면 "표에 없다" 와 "물음표를 그리라고 했다" 가 화면에서 같아
     *    보인다. 한글이 들어올 때 특히 나쁘다. */
    if (cp < FIRST_CP || cp > LAST_CP) {
        return (const uint8_t *)0;
    }
    return &GLYPHS[(cp - FIRST_CP) * GLYPH_W];
}

/* 🔴 advance = 6 이다(폭 5 + 자간 1). 자간이 없으면 "11" 이 한 글자처럼
 *    보인다 — 숫자를 읽는 화면에서 치명적이다. */
static const MkFont ASCII_5X7 = { GLYPH_W, 7u, 6u, 1u, ascii_glyph };

const MkFont *mk_font_ascii5x7(void)
{
    return &ASCII_5X7;
}
